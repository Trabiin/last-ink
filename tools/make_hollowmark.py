#!/usr/bin/env python3
"""Builds maps/hollowmark.txt: the hub town laid out like a lived-in place (docs/ART_STYLE.md, "Town layout").

A winding road comes up from the south gate into an irregular square; lanes branch off it; buildings stand at
their own angles along them, and every front door has a trodden footpath (",") to the nearest street.
Buildings are placed by their BOTTOM-CENTRE tile here; 5x5 plots and big props are written at their top-left
tile, which is what the map format expects. Edit the tables below and rerun:
    python3 tools/make_hollowmark.py
"""
import os
import random
from collections import deque

W, H = 46, 32
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "maps", "hollowmark.txt")

HEADER = """# Last Ink map: Hollowmark, the hub town (46 x 32 tiles of 16px). Generated by tools/make_hollowmark.py:
# edit that script, not this file.
# Same legend as frayed_meadow.txt, plus the town lines below:
#   @prop<char> kind|NAME   places a prop kind (see scripts/prop.gd) with an optional name board
#   @mark<char> id          marks a spot: recruit posts, the Command Table, building plots (top-left
#                           tile of a 5x5 plot, site_<building id>) and the Wardlamp
#   @dirt <chars>           characters that sit on the paving (plaza markers)
#   ,                       a trodden footpath (up to a front door)
@name Hollowmark
@ground town
@propH townhall|TOWN HALL
@propI tavern|THE SPILT INK
@propJ stores|STORES
@propF fountain
@propM stall
@propP produce
@propX crates
@propU barrels
@propN bench
@propV banner
@propG grave
@propO well
@propQ cart
@propZ noticeboard
@propl lamppost
@propa house_a
@propc house_c
@propd house_d
@prope house_e
@propj house_f
@propk house_g
@propn house_h
@propo fence
@propp garden
@propR tree
@markC table
@markh hall
@markv tavern
@markq stores
@markg graveyard
@markw gate
@markm market
@markx table_side
@marky well
@marki bench
@markA site_barracks
@markB site_infirmary
@markD site_inkworks
@markE site_scriptorium
@markK site_guildhall
@markW site_forge
@marku site_market
@markL lamp
@markY visitors
@dirt CFMPNVhvqwmx12LOQZlXUi
@sign1 THE INKLANDS  (south)|Missions leave from the Command Table
@sign2 HOLLOWMARK|~~pop. 212~~   ~~pop. 40~~   pop. you
---
"""

g = [['.' for _ in range(W)] for _ in range(H)]


def disc(cx, cy, rx, ry, ch=':'):
    for y in range(H):
        for x in range(W):
            if ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1:
                g[y][x] = ch


def road(pts, r):
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        n = int(max(abs(x1 - x0), abs(y1 - y0)) * 3) + 1
        for i in range(n + 1):
            t = i / n
            disc(x0 + (x1 - x0) * t, y0 + (y1 - y0) * t, r, r * 0.85)


# ---------------------------------------------------------------- streets
disc(23, 14.5, 9.0, 4.6)                                   # the square
road([(24, 31), (24, 28), (22, 25), (21, 22), (22, 19)], 2.0)  # the road up from the south gate
road([(15, 14), (11, 13), (7, 11), (3, 10), (0, 10)], 1.5)     # west lane
road([(31, 13), (35, 11), (39, 9), (43, 8), (45, 8)], 1.5)     # east lane, past the stores
road([(29, 18), (33, 21), (37, 24), (41, 25)], 1.3)           # south-east alley
road([(17, 18), (13, 21), (9, 23)], 1.2)                      # alley to the graveyard
random.seed(7)
for y in range(H):  # ragged edges
    for x in range(W):
        if g[y][x] == ':' and random.random() < 0.04:
            g[y][x] = '.'

# ---------------------------------------------------------------- buildings (bottom-centre tile) and doors
# char -> door offset in tiles from the bottom-centre (for the footpath)
BIG = {  # 5x5 kinds and plots: written at top-left = (x - 2, y - 5)
    (23, 9): 'H',   # town hall, heading the square
    (33, 9): 'I',   # tavern, on the square's north-east corner
    (40, 7): 'J',   # stores, up the east lane
    (8, 9): 'A',    # barracks, west lane
    (14, 9): 'B',   # infirmary
    (38, 20): 'D',  # inkworks, south-east alley
    (31, 26): 'E',  # scriptorium
    (12, 19): 'K',  # guildhall, by the graveyard alley
    (4, 18): 'W',   # forge, west of the guildhall, downwind of the square (issue #112)
    (17, 27): 'u',  # market, by the gate road where carts come in (issue #112)
}
DOOR = {'H': 0, 'I': 0, 'J': 0, 'A': 0, 'B': 0, 'D': 0, 'E': 0, 'K': 0, 'W': 0, 'u': 0,
        'a': 0, 'b': 0, 'c': 1, 'd': -1, 'e': 0, 'j': 1, 'k': -1, 'n': 0}
HOUSES = {  # free-standing art, written at the bottom-centre tile
    (3, 7): 'a', (44, 16): 'c', (44, 5): 'd',
    (40, 30): 'k', (29, 31): 'n',
}
MARKS = {
    (21, 13): 'C', (24, 12): 'h', (31, 11): 'v', (38, 9): 'q', (6, 25): 'g', (24, 30): 'w',
    (27, 17): 'm', (22, 19): '@', (19, 15): 'x', (26, 15): 'L', (23, 27): 'Y',
    (32, 16): 'y', (17, 18): 'i',  # posts by the well and the plaza bench (issue #27: room for more recruits)
}
PROPS = {
    (23, 16): 'F', (29, 15): 'M', (27, 14): 'P', (20, 12): 'V', (25, 12): 'V',
    (34, 13): 'O', (17, 17): 'N', (31, 17): 'Z', (19, 21): 'Q',
    (36, 10): 'X', (37, 10): 'U', (29, 10): 'U', (16, 11): 'X', (11, 10): 'U', (42, 9): 'X',
    (35, 22): 'U', (27, 22): 'X', (10, 20): 'U',
    (15, 15): 'l', (32, 14): 'l', (21, 24): 'l', (26, 25): 'l', (9, 12): 'l', (36, 19): 'l',
    (22, 29): '1', (17, 14): '2',
    # graveyard
    (3, 24): 'G', (5, 24): 'G', (7, 24): 'G', (3, 27): 'G', (5, 27): 'G', (8, 27): 'G', (4, 29): 'G',
    # greenery and gardens
    (1, 2): 'R', (12, 2): 'R', (44, 24): 'R', (1, 14): 'R', (35, 29): 'R', (10, 30): 'R', (44, 21): 'R',
    (6, 4): 'p', (20, 4): 'p', (6, 20): 'p', (14, 28): 'p', (42, 27): 'p',
    (2, 4): 'o', (9, 4): 'o', (16, 4): 'o', (2, 21): 'o', (12, 27): 'o', (43, 31): 'o',
    (30, 2): 'f', (11, 16): 'f', (41, 16): 'f', (19, 29): 'f',
}

# Footpaths: from each door to the nearest street cell, routed round the other buildings.
blocked = set()
for (x, y) in list(BIG) + list(HOUSES):
    for yy in range(y - 3, y + 1):
        for xx in range(x - 3, x + 4):
            blocked.add((xx, yy))
street = {(x, y) for y in range(H) for x in range(W) if g[y][x] == ':'}
for (x, y), c in list(BIG.items()) + list(HOUSES.items()):
    start = (x + DOOR[c], y + 1)
    if start in street:
        continue
    prev = {start: None}
    q = deque([start])
    end = None
    while q:
        cur = q.popleft()
        if cur in street:
            end = cur
            break
        cx, cy = cur
        for nx, ny in ((cx, cy + 1), (cx - 1, cy), (cx + 1, cy), (cx, cy - 1)):
            if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in prev and (nx, ny) not in blocked:
                prev[(nx, ny)] = cur
                q.append((nx, ny))
    cur = prev.get(end) if end else None
    while cur is not None:
        g[cur[1]][cur[0]] = ','
        cur = prev[cur]
    for dx in (-1, 0, 1):
        sx = start[0] + dx
        if 0 <= sx < W and start[1] < H and g[start[1]][sx] == '.':
            g[start[1]][sx] = ','

for (x, y), c in BIG.items():
    for yy in range(y - 5, y):  # the 5x5 footprint stays grass under the building
        for xx in range(x - 2, x + 3):
            if 0 <= xx < W and 0 <= yy < H and g[yy][xx] == ':':
                g[yy][xx] = '.'
    g[y - 5][x - 2] = c
for (x, y), c in list(HOUSES.items()) + list(MARKS.items()) + list(PROPS.items()):
    if 0 <= x < W and 0 <= y < H:
        g[y][x] = c
for x in range(W):  # hedge row along the north edge
    if g[0][x] == '.' and random.random() < 0.55:
        g[0][x] = 't'

with open(OUT, "w") as f:
    f.write(HEADER + "\n".join("".join(r) for r in g) + "\n")
print("\n".join("".join(r) for r in g))
